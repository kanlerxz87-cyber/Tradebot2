#!/usr/bin/env python3
"""Publish the site to the repository root.

GitHub Pages for this repo has already been observed serving the repository
**root** (build_type=legacy), while the project's own deploy workflow publishes
`docs/`. Serving one and testing the other is how a site ends up "deployed" but
blank, so this script makes the root a complete, self-contained copy of `docs/`:

    python3 pages_build.py          # write the root copy
    python3 pages_build.py --check  # fail if the root copy is stale

The root copy is generated, never hand-edited, and committed so either Pages
mode serves a working dashboard.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = ROOT / "docs"
MARKER = "<!-- generated by pages_build.py from docs/ — do not edit this copy -->"
MANIFEST = ".pages_build.json"   # records exactly which root files this script owns

# files/dirs copied verbatim from docs/ into the repo root
COPY = ["styles.css", "data", "js"]
PAGES = sorted(p.name for p in DOCS.glob("*.html"))


def expected() -> dict[Path, str]:
    """Map of root-relative path -> exact expected content."""
    out: dict[Path, str] = {}
    for page in PAGES:
        text = (DOCS / page).read_text(encoding="utf-8")
        out[Path(page)] = text.replace("<head>", f"<head>\n{MARKER}", 1)
    for name in COPY:
        src = DOCS / name
        if src.is_dir():
            for f in sorted(src.rglob("*")):
                if f.is_file():
                    out[f.relative_to(DOCS)] = f.read_text(encoding="utf-8")
        else:
            out[Path(name)] = src.read_text(encoding="utf-8")
    return out


def main() -> int:
    check_only = "--check" in sys.argv
    want = expected()
    problems: list[str] = []
    for rel, text in want.items():
        target = ROOT / rel
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        if check_only:
            problems.append(f"stale: {rel}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")

    # Remove only files this script previously generated and no longer produces.
    # Files owned by other sessions are NEVER touched, even inside data/ or js/.
    manifest_path = ROOT / MANIFEST
    previous: list[str] = []
    if manifest_path.exists():
        try:
            previous = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", [])
        except json.JSONDecodeError:
            previous = []
    owned = {str(rel) for rel in want}
    for stale in sorted(set(previous) - owned):
        target = ROOT / stale
        if not target.exists():
            continue
        text = target.read_text(encoding="utf-8")
        if MARKER not in text and (ROOT / "docs" / stale).exists() is False and not stale.startswith(("data/", "js/", "styles.css")):
            continue  # not ours; leave it alone
        if check_only:
            problems.append(f"stale: {stale}")
        else:
            target.unlink()
            print(f"removed previously generated {stale}")

    if not check_only:
        manifest_path.write_text(
            json.dumps({"generated_from": "docs/", "files": sorted(owned)}, indent=1) + "\n",
            encoding="utf-8")

    if check_only:
        for p in problems:
            print("  " + p)
        print(f"{len(want)} files, {len(problems)} problem(s)")
        return 1 if problems else 0
    print(f"root copy is up to date ({len(want)} files, {len(PAGES)} pages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
